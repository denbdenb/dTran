    static const StringEntry* GetTableForLanguage(std::wstring_view langCode, size_t& outCount)
    {
        outCount = 84;
        if (langCode == L"en") return s_strings_en;
        if (langCode == L"ru") return s_strings_ru;
        if (langCode == L"es") return s_strings_es;
        if (langCode == L"de") return s_strings_de;
        if (langCode == L"fr") return s_strings_fr;
        if (langCode == L"pt-BR") return s_strings_pt_BR;
        if (langCode == L"it") return s_strings_it;
        if (langCode == L"ja") return s_strings_ja;
        if (langCode == L"ko") return s_strings_ko;
        if (langCode == L"zh-Hans") return s_strings_zh_Hans;
        return nullptr;
    }

    static const wchar_t* LookupInTable(const StringEntry* table, size_t count, std::wstring_view key)
    {
        auto it = std::lower_bound(table, table + count, key, [](const StringEntry& entry, std::wstring_view k) {
            return std::wstring_view(entry.key) < k;
        });
        if (it != table + count && std::wstring_view(it->key) == key)
        {
            return it->value;
        }
        return nullptr;
    }

    LocalizationManager& LocalizationManager::Instance()
    {
        static LocalizationManager instance;
        return instance;
    }

    LocalizationManager::LocalizationManager()
    {
        auto const& s = SettingsManager::Instance().GetSettings();
        if (IsValidLanguage(s.appLanguage))
        {
            m_currentLang = s.appLanguage;
        }
        else
        {
            m_currentLang = L"en";
        }
    }

    bool LocalizationManager::IsValidLanguage(std::wstring_view langCode)
    {
        size_t count = 0;
        return GetTableForLanguage(langCode, count) != nullptr;
    }

